// Build a single file for pasting into the Cloudflare dashboard. No dependencies.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const services = JSON.parse(await readFile(new URL('data/services.json', root), 'utf8'));
const source = await readFile(new URL('backend/webhook.mjs', root), 'utf8');
const importLine = "import services from '../data/services.json' with { type: 'json' };";
if (!source.includes(importLine)) throw new Error('Catalog import changed; update bundler.');
const accountImport = "import { accountAPI } from './account.mjs';";
if (!source.includes(accountImport)) throw new Error('Account module import changed; update bundler.');
const account = await readFile(new URL('backend/account.mjs', root), 'utf8');
// Keep module-local names in an IIFE when producing the standalone dashboard file.
const accountBundle = 'const accountAPI = (() => {\n' + account.replaceAll('export async function ', 'async function ') + '\nreturn accountAPI;\n})();';
const output = '// Generated by node scripts/build-worker.mjs — edit backend/webhook.mjs and backend/account.mjs instead.\n'
  + source.replace(importLine, `const services = ${JSON.stringify(services, null, 2)};`).replace(accountImport, accountBundle);
await mkdir(new URL('deploy/', root), { recursive: true });
await writeFile(new URL('deploy/worker.mjs', root), output);
console.log('Built deploy/worker.mjs (no credentials embedded)');
